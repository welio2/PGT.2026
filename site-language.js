    const supportedLanguages = Object.keys(locales);
    let currentLanguage = 'pt-BR';
    let storageError = null;

    try {
        const savedLanguage = localStorage.getItem(storageKey);
        if (supportedLanguages.includes(savedLanguage)) currentLanguage = savedLanguage;
    } catch (error) {
        storageError = error;
        console.error('Não foi possível carregar o idioma salvo.', error);
    }

    function translate(key, values) {
        const dictionary = translations[currentLanguage] || translations['pt-BR'];
        const message = dictionary[key] || translations['pt-BR'][key] || key;
        return message.replace(/\{(\w+)\}/g, (placeholder, name) => (
            values && Object.prototype.hasOwnProperty.call(values, name)
                ? String(values[name])
                : placeholder
        ));
    }

    function translateAchievementName(name) {
        const translationsForName = achievementNameTranslations[name];
        if (!translationsForName) return name;
        const localeIndex = achievementNameLanguages.indexOf(currentLanguage);
        return translationsForName[localeIndex] || name;
    }

    function applyTranslations() {
        document.documentElement.lang = locales[currentLanguage];
        document.querySelectorAll('[data-i18n]').forEach((element) => {
            element.textContent = translate(element.dataset.i18n);
        });
        document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
            element.setAttribute('aria-label', translate(element.dataset.i18nAriaLabel));
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
            element.setAttribute('placeholder', translate(element.dataset.i18nPlaceholder));
        });
        document.querySelectorAll('[data-i18n-play]').forEach((element) => {
            element.textContent = `${translate('play')} ${translate(element.dataset.i18nPlay)}`;
        });
        const languageSelect = document.getElementById('language-select');
        if (languageSelect) languageSelect.value = currentLanguage;
        const title = document.querySelector('title[data-i18n]');
        if (title) document.title = translate(title.dataset.i18n);
        if (storageError) {
            const status = document.getElementById('language-status');
            if (status) status.textContent = translate('languageSaveError');
        }
    }

    function setLanguage(language) {
        if (!supportedLanguages.includes(language)) return;
        currentLanguage = language;
        storageError = null;
        try {
            localStorage.setItem(storageKey, language);
        } catch (error) {
            storageError = error;
            console.error('Não foi possível salvar o idioma selecionado.', error);
        }
        applyTranslations();
        window.dispatchEvent(new Event('buuro-language-changed'));
    }

    window.BuuroLanguage = {
        get current() {
            return currentLanguage;
        },
        translate,
        translateAchievementName,
        set: setLanguage,
        apply: applyTranslations
    };

    document.addEventListener('DOMContentLoaded', () => {
        applyTranslations();
        const languageSelect = document.getElementById('language-select');
        if (languageSelect) {
            languageSelect.addEventListener('change', () => setLanguage(languageSelect.value));
        }
    });

    window.addEventListener('storage', (event) => {
        if (event.key !== storageKey && event.key !== null) return;
        const savedLanguage = event.key === null ? null : event.newValue;
        currentLanguage = supportedLanguages.includes(savedLanguage) ? savedLanguage : 'pt-BR';
        storageError = null;
        applyTranslations();
        window.dispatchEvent(new Event('buuro-language-changed'));
    });
